export function getUserEnrolledCourses(userid: number): MoodleEnrolledCourse[] {
  const userEnrollments = mockEnrollments.filter(e => e.userid === userid);

  return userEnrollments.map(enrollment => {
    const course = mockCourses.find(c => c.id === enrollment.courseid);
    if (!course) return null;

    return {
      id: course.id,
      shortname: course.shortname,
      fullname: course.fullname,
      displayname: course.displayname,
      enrolledusercount: course.enrolledusercount || 0,
      idnumber: course.idnumber,
      visible: course.visible,
      summary: course.summary,
      summaryformat: course.summaryformat,
      format: course.format,
      showgrades: course.showgrades,
      lang: course.lang,
      enablecompletion: course.enablecompletion,
      completionhascriteria: course.completionhascriteria ? 1 : 0,
      completionusertracked: 1,
      category: course.categoryid,
      progress: enrollment.progress,
      completed: enrollment.completed,
      startdate: course.startdate,
      enddate: course.enddate,
      marker: 0,
      lastaccess: enrollment.timemodified,
      isfavourite: false,
      hidden: false,
      overviewfiles: [],
    } as MoodleEnrolledCourse;
  }).filter(Boolean) as MoodleEnrolledCourse[];
}

